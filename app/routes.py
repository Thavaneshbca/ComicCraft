@router.post("/generate", response_class=HTMLResponse, summary="Form-based Comic Generation")
async def generate_comic_form(
    request: Request,
    story_prompt: str = Form(..., description="Story premise"),
    character_name: str = Form(..., description="Protagonist name"),
    setting: str = Form(..., description="Setting / location"),
    tone: str = Form("Dramatic", description="Narrative tone"),
    art_style: str = Form("Comic Book", description="Artistic style"),
):
    """Handle HTML form submission, execute AI pipeline, and render comic preview."""
    try:
        story_prompt = story_prompt.strip()
        character_name = character_name.strip()
        setting = setting.strip()
        tone = tone.strip()
        art_style = art_style.strip()

        if not story_prompt or not character_name or not setting:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Story prompt, character name, and setting are required.",
            )

        logger.info(
            "Generating comic for '%s' in '%s' (tone=%s, style=%s)...",
            character_name,
            setting,
            tone,
            art_style,
        )

        # Step 1: Generate 5-panel outline via Gemini Flash
        full_user_prompt = (
            f"{story_prompt}\n"
            f"The main character is {character_name}.\n"
            f"The setting is {setting}.\n"
            f"The tone is {tone}. The art style is {art_style}."
        )
        outline = generate_outline(
            user_prompt=full_user_prompt,
            character_name=character_name,
            setting=setting,
            tone=tone,
            art_style=art_style,
        )

        if not isinstance(outline, list) or not outline:
            raise ValueError("Invalid outline generated by AI service.")

        # Step 2: Generate detailed story & dialogue via Gemini Pro
        full_story = generate_story(
            outline=outline,
            character_name=character_name,
            tone=tone,
        )

        # Step 3: Generate comic illustrations
        images = []
        for panel in outline:
            prompt_text = panel.get("image_prompt", "")
            img_path = generate_image(prompt_text)
            images.append(img_path)

        # Step 4: Build complete layout
        layout = build_comic_layout(images, full_story, outline)

        # Step 5: Export to multi-page PDF
        comic_title = f"{character_name}: {setting} Chronicles"
        pdf_path = save_pdf(layout, comic_title=comic_title)
        web_pdf_path = "/" + pdf_path.lstrip("/")

        return templates.TemplateResponse(
            request=request,
            name="comic_preview.html",
            context={
                "layout": layout,
                "pdf_path": web_pdf_path,
                "comic_title": comic_title,
                "story_prompt": story_prompt,
                "character_name": character_name,
                "setting": setting,
                "tone": tone,
                "art_style": art_style,
            },
        )

    except HTTPException:
        raise
    except Exception as exc:
        traceback.print_exc()
        logger.error("Comic generation failed: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Comic generation encountered an error: {str(exc)}",
        )


@router.post(
    "/generate-comic/json",
    response_model=ComicGenerationResponse,
    summary="JSON API Comic Generation",
)
async def generate_comic_json(payload: PromptRequest):
    """Generate complete comic from JSON payload and return structured data with PDF path."""
    try:
        # Step 1: Generate 5-panel outline
        full_user_prompt = (
            f"{payload.story_prompt}\n"
            f"The main character is {payload.character_name}.\n"
            f"The setting is {payload.setting}.\n"
            f"The tone is {payload.tone}. The art style is {payload.art_style}."
        )
        outline = generate_outline(
            user_prompt=full_user_prompt,
            character_name=payload.character_name,
            setting=payload.setting,
            tone=payload.tone,
            art_style=payload.art_style,
        )

        # Step 2: Generate detailed story
        full_story = generate_story(
            outline=outline,
            character_name=payload.character_name,
            tone=payload.tone,
        )

        # Step 3: Generate illustrations
        images = []
        for panel in outline:
            prompt_text = panel.get("image_prompt", "")
            img_path = generate_image(prompt_text)
            images.append(img_path)

        # Step 4: Build layout
        layout = build_comic_layout(images, full_story, outline)

        # Step 5: Save PDF
        comic_title = f"{payload.character_name}'s Tale in {payload.setting}"
        pdf_path = save_pdf(layout, comic_title=comic_title)
        web_pdf_path = "/" + pdf_path.lstrip("/")

        # Convert layout dictionaries into Pydantic models
        panel_models = [ComicPanel(**p) for p in layout]

        return ComicGenerationResponse(
            status="success",
            message="Comic generated successfully",
            story_prompt=payload.story_prompt,
            character_name=payload.character_name,
            setting=payload.setting,
            tone=payload.tone,
            art_style=payload.art_style,
            panels=panel_models,
            pdf_path=web_pdf_path,
            download_url=web_pdf_path,
        )

    except Exception as exc:
        traceback.print_exc()
        logger.error("JSON comic generation failed: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"JSON Comic generation failed: {str(exc)}",
        )


