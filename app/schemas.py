"""Pydantic schemas for ComicCraft."""

from typing import List, Optional
from pydantic import BaseModel, Field


class PromptRequest(BaseModel):
    """Schema for incoming comic generation request via JSON or Form."""

    story_prompt: str = Field(
        ...,
        description="Core story premise or narrative summary",
        min_length=3,
        max_length=1500,
        examples=["A brave fox named Rusty explores an enchanted glowing forest seeking a legendary crystal."],
    )
    character_name: str = Field(
        ...,
        description="Name of the main character / protagonist",
        min_length=1,
        max_length=100,
        examples=["Rusty the Fox"],
    )
    setting: str = Field(
        ...,
        description="Primary setting / backdrop of the comic strip",
        min_length=1,
        max_length=100,
        examples=["Enchanted Forest"],
    )
    tone: str = Field(
        default="Dramatic",
        description="Story mood or narrative tone (e.g., Dramatic, Funny, Light-hearted, Poetic, Adventure)",
        max_length=50,
        examples=["Adventure"],
    )
    art_style: str = Field(
        default="Comic Book",
        description="Visual illustration style (e.g., Comic Book, Anime, Pixel Art, Realistic, Fantasy Illustration)",
        max_length=50,
        examples=["Comic Book"],
    )


class ComicPanel(BaseModel):
    """Structured representation of an individual comic panel."""

    panel_number: int = Field(..., description="Sequential index of the panel (1 through 5)")
    title: str = Field(..., description="Descriptive title of the panel scene")
    scene_description: str = Field(..., description="Visual scene summary and context")
    image_prompt: str = Field(..., description="Detailed visual prompt tailored for diffusion model")
    narration: Optional[str] = Field(default="", description="Storyteller narration text")
    dialogue: Optional[str] = Field(default="", description="Character spoken lines or exclamation")
    caption: Optional[str] = Field(default="", description="Atmospheric caption or ambient sound")
    image_path: Optional[str] = Field(default="", description="Filesystem path of the generated illustration")
    web_image_path: Optional[str] = Field(default="", description="URL/browser accessible path for the image")
    text: Optional[str] = Field(default="", description="Combined story text for PDF/preview formatting")


class ComicOutline(BaseModel):
    """5-panel comic outline generated by Gemini Flash."""

    panels: List[ComicPanel] = Field(..., min_length=5, max_length=5, description="List of exactly 5 comic panels")


class ComicGenerationResponse(BaseModel):
    """Structured response returned by the JSON generation API."""

    status: str = Field("success", description="Status string: success or error")
    message: str = Field("Comic generated successfully", description="Informational message")
    story_prompt: str
    character_name: str
    setting: str
    tone: str
    art_style: str
    panels: List[ComicPanel]
    pdf_path: str = Field(..., description="Saved PDF relative or filesystem path")
    download_url: str = Field(..., description="Web URL endpoint to download the PDF")


class TestImageRequest(BaseModel):
    """Request payload for testing image generation directly."""

    prompt: str = Field(
        ...,
        min_length=3,
        description="Visual description to render",
        examples=["A futuristic cyberpunk street in neon rain, comic art style"],
    )


class TestImageResponse(BaseModel):
    """Response payload for image test endpoint."""

    status: str = Field("success")
    message: str
    prompt: str
    image_path: str
    web_image_path: str
